import React, { useEffect, useRef, useState } from 'react';
import { doc, getDocFromServer, serverTimestamp, setDoc } from 'firebase/firestore';
import { BrainCircuit, Check, Lightbulb,
  RotateCcw, ShieldCheck, Sparkles } from 'lucide-react';
import { db, appId } from '../../firebase/config';
import ContextConsentPanel from './ContextConsentPanel';
import StagingSecurityAuditPanel from './StagingSecurityAuditPanel';
import StagingConsentEndpointAuditPanel from './StagingConsentEndpointAuditPanel';
import {
  AI_SETTINGS_DEFAULTS, parseAiSettings, settingsEqual, updateAiPreference
} from './aiSettingsModel';

const settingsPath = uid =>
  `artifacts/${appId}/users/${uid}/aiSettings/preferences`;

// Expose only a small set of technical error categories, never UID/path/content.
const safeFirestoreErrorCode = error => {
  const allowed = ['permission-denied', 'unauthenticated', 'unavailable',
    'deadline-exceeded', 'cancelled', 'readback-mismatch'];
  return allowed.includes(error?.code) ? error.code : 'unknown';
};

const SelectRow = ({ label, description, name, value, options, onChange, disabled }) => (
  <label className="reflect-ai-settings-row">
    <span className="reflect-ai-settings-row-text">
      <strong>{label}</strong><span>{description}</span>
    </span>
    <select value={value} disabled={disabled}
      onChange={event => onChange(name, event.target.value)}>
      {options.map(([id, caption]) => <option value={id} key={id}>{caption}</option>)}
    </select>
  </label>
);

const ToggleRow = ({ label, description, name, checked, onChange, disabled }) => (
  <label className="reflect-ai-settings-row reflect-ai-settings-toggle-row">
    <span className="reflect-ai-settings-row-text">
      <strong>{label}</strong><span>{description}</span>
    </span>
    <input type="checkbox" checked={checked} disabled={disabled}
      onChange={event => onChange(name, event.target.checked)}/>
  </label>
);

/**
 * These account-scoped preferences are saved, but are NOT automatically
 * consent grants or active behavioral controls on the current Grok handler.
 * No transcript is fetched, sent or generated by this screen.
 */
export default function AISettings({ userId, sessions = [] }) {
  const [draft, setDraft] = useState({ ...AI_SETTINGS_DEFAULTS });
  const [saved, setSaved] = useState({ ...AI_SETTINGS_DEFAULTS });
  const [status, setStatus] = useState('loading');
  const [feedback, setFeedback] = useState('');
  const [loadErrorCode, setLoadErrorCode] = useState(null);
  const activeOwner = useRef(userId);
  activeOwner.current = userId;

  useEffect(() => {
    let cancelled = false;
    setDraft({ ...AI_SETTINGS_DEFAULTS });
    setSaved({ ...AI_SETTINGS_DEFAULTS });
    setFeedback('');
    setLoadErrorCode(null);
    setStatus('loading');
    if (!userId || !db) {
      setStatus('load-error');
      return undefined;
    }
    // A cached document is insufficient for account-level persistence verification.
    // On network failure block writes rather than display defaults as server state.
    getDocFromServer(doc(db, settingsPath(userId))).then(snapshot => {
      if (cancelled) return;
      if (!snapshot.exists()) {
        setStatus('ready');
        return;
      }
      const parsed = parseAiSettings(snapshot.data());
      if (!parsed) {
        setStatus('invalid'); // fail closed; never turn on old/unknown consent flags
        return;
      }
      setDraft(parsed); setSaved(parsed); setStatus('ready');
    }).catch(error => {
      if (!cancelled) {
        setLoadErrorCode(safeFirestoreErrorCode(error));
        setStatus('load-error');
      }
    });
    return () => { cancelled = true; };
  }, [userId]);

  const change = (name, value) => {
    setFeedback('');
    setDraft(current => updateAiPreference(current, name, value));
  };

  const save = async event => {
    event.preventDefault();
    if (!userId || !db || !['ready', 'invalid', 'save-error'].includes(status)) return;
    const validated = parseAiSettings(draft);
    if (!validated) {
      setFeedback('Некорректные параметры. Сохранение отменено.');
      return;
    }
    const savingUid = userId;
    setStatus('saving'); setFeedback('');
    let writeAcknowledged = false;
    try {
      const preferenceRef = doc(db, settingsPath(savingUid));
      await setDoc(preferenceRef, {
        ...validated, updatedAt: serverTimestamp()
      });
      writeAcknowledged = true;
      // Verify the server document, not a possibly stale local Firestore cache.
      const serverSnapshot = await getDocFromServer(preferenceRef);
      const confirmed = serverSnapshot.exists()
        ? parseAiSettings(serverSnapshot.data()) : null;
      if (!confirmed || !settingsEqual(confirmed, validated)) {
        throw Object.assign(new Error('Settings readback mismatch'),
          { code: 'readback-mismatch' });
      }
      if (activeOwner.current !== savingUid) return;
      setSaved(confirmed);
      setStatus('ready');
      setFeedback('Настройки сохранены и подтверждены сервером. Подключение к AI backend ещё не выполнено.');
    } catch (error) {
      if (activeOwner.current !== savingUid) return;
      const code = safeFirestoreErrorCode(error);
      setStatus('save-error');
      setFeedback(writeAcknowledged
        ? `Запись отправлена, но серверное чтение не подтвердило значения (код: ${code}). Изменения сохранены в форме; повторите проверку позже.`
        : `Сохранение не подтверждено (код: ${code}). Изменения оставлены в форме, можно повторить.`);
    }
  };

  const busy = status === 'loading' || status === 'saving';
  const hasUnsavedChanges = !settingsEqual(draft, saved);
  const dirty = hasUnsavedChanges || status === 'invalid';
  const disabled = busy || status === 'load-error';

  useEffect(() => {
    if (!hasUnsavedChanges || !userId || !['ready', 'invalid', 'save-error'].includes(status)) {
      return undefined;
    }
    // The native browser confirmation is best-effort (browser-dependent).
    const warnBeforeReload = event => {
      event.preventDefault();
      event.returnValue = '';
    };
    window.addEventListener('beforeunload', warnBeforeReload);
    return () => window.removeEventListener('beforeunload', warnBeforeReload);
  }, [hasUnsavedChanges, status, userId]);

  return (
    <section className="reflect-ai-settings" aria-label="Настройки AI">
      <div className="reflect-ai-settings-heading">
        <span className="reflect-ai-settings-kicker"><Sparkles size={16}/> Личный ассистент</span>
        <h2>Настройки Reflect AI</h2>
        <p>Здесь сохраняются предпочтения. Разрешения на доступ к истории
          управляются отдельно и не включают чтение истории моделью Grok.
          Текущие ответы Grok эти настройки пока не изменяют.</p>
      </div>
      <div className="reflect-ai-settings-notice" role="note">
        <ShieldCheck size={18} aria-hidden="true"/>
        <span><strong>Сохранение ≠ разрешение на чтение данных.</strong> История, дневник,
          цели и карта тела не становятся доступными ИИ при включении этих параметров.</span>
      </div>

      {status === 'loading' && <p role="status">Загружаем настройки аккаунта…</p>}
      {status === 'load-error' && <p role="alert" className="reflect-ai-settings-error">
        Не удалось прочитать настройки. Чтобы не перезаписать существующие данные,
        редактирование заблокировано. Проверьте доступ и откройте страницу заново.
        {loadErrorCode && <span> Код ошибки: {loadErrorCode}.</span>}
      </p>}
      {status === 'invalid' && <p role="alert" className="reflect-ai-settings-error">
        Сохранённые настройки имеют неизвестный формат. Показаны безопасные значения
        по умолчанию. Нажмите «Сохранить», только если хотите заменить старую версию.
      </p>}

      {status !== 'loading' && status !== 'load-error' && (
        <form className="reflect-ai-settings-form" onSubmit={save}>
          <div className="reflect-ai-settings-card">
            <div className="reflect-ai-settings-card-title">
              <BrainCircuit size={19}/><h3>Формат диалога</h3>
            </div>
            <SelectRow label="Глубина ответа" description="Предпочитаемая длина и детализация."
              name="responseDepth" value={draft.responseDepth} disabled={disabled}
              onChange={change} options={[
                ['concise', 'Кратко'], ['balanced', 'Сбалансированно'], ['deep', 'Подробно']
              ]}/>
            <SelectRow label="Тон общения" description="Подход, который вам комфортнее."
              name="responseTone" value={draft.responseTone} disabled={disabled}
              onChange={change} options={[
                ['supportive', 'Поддержка'], ['analytical', 'Анализ'], ['strategic', 'Стратегия']
              ]}/>
            <ToggleRow label="Уточняющие вопросы"
              description="Предпочтение: спрашивать, когда ситуация неясна, вместо поверхностного вывода."
              name="askClarifyingQuestions" checked={draft.askClarifyingQuestions}
              onChange={change} disabled={disabled}/>
          </div>

          <div className="reflect-ai-settings-card">
            <div className="reflect-ai-settings-card-title">
              <Lightbulb size={19}/><h3>Рекомендации</h3>
            </div>
            <ToggleRow label="Предлагать рекомендации"
              description="По умолчанию выключено. Не включает фактическую генерацию до подключения серверного контроля."
              name="recommendationsEnabled" checked={draft.recommendationsEnabled}
              onChange={change} disabled={disabled}/>
            <SelectRow label="Частота"
              description="В будущем рекомендации не должны повторяться и навязываться."
              name="recommendationFrequency" value={draft.recommendationFrequency}
              onChange={change} disabled={disabled || !draft.recommendationsEnabled}
              options={[['rare', 'Редко'], ['balanced', 'Умеренно']]}/>
            <ToggleRow label="Автосохранение рекомендаций"
              description="В будущем сохранять одобренные сервером рекомендации как отдельный тип записи."
              name="autoSaveRecommendations" checked={draft.autoSaveRecommendations}
              onChange={change} disabled={disabled || !draft.recommendationsEnabled}/>
            <ToggleRow label="Индикатор достаточности контекста"
              description="Показывать проверенную полноту контекста. Сейчас индикатор ещё не подключён."
              name="showContextIndicator" checked={draft.showContextIndicator}
              onChange={change} disabled={disabled}/>
          </div>

          {/* Consent management is deliberately separate from AI preferences. */}

          {feedback && <p role={status === 'save-error' ? 'alert' : 'status'}
            className={status === 'save-error' ? 'reflect-ai-settings-error' : 'reflect-ai-settings-feedback'}>
            {status === 'ready' && <Check size={16} aria-hidden="true"/>}{feedback}
          </p>}
          {hasUnsavedChanges && status !== 'saving' && (
            <p role="status" className="reflect-ai-settings-feedback">
              Есть несохранённые изменения. Нажмите «Сохранить настройки» до обновления страницы.
            </p>
          )}
          <div className="reflect-ai-settings-form-actions">
            <button type="button" className="reflect-ai-settings-reset" disabled={busy || !dirty}
              onClick={() => { setDraft({ ...saved }); setFeedback(''); }}>
              <RotateCcw size={16} aria-hidden="true"/> Отменить изменения
            </button>
            <button type="submit" className="reflect-ai-settings-save"
              disabled={busy || (!dirty && status !== 'save-error')}>
              <Check size={16} aria-hidden="true"/>
              {status === 'saving' ? 'Сохраняется…' : 'Сохранить настройки'}
            </button>
          </div>
        </form>
      )}
      <ContextConsentPanel userId={userId} sessions={sessions}/>
      <StagingSecurityAuditPanel userId={userId}/>
      <StagingConsentEndpointAuditPanel userId={userId}/>
    </section>
  );
}
